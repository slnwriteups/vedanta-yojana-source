import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadBooks, loadDivyaDesams } from "../content-lib/loader.ts";
import { allPasuramResourceUrls } from "../content-lib/pasuram-resources.ts";
import { getPasuramFileName } from "../services/pasuramResourceId.ts";

/**
 * Emits mobile/content-lib/pasuram-origin.generated.ts: the byte length
 * of each ORIGINAL Prapatti.com PDF as it was when we bundled it (the
 * raw files under mobile/assets/pasurams/, before qpdf optimization).
 *
 * services/pasuramLatest.ts uses this during its periodic background
 * check: a HEAD request to Prapatti.com returns the current file's
 * Content-Length, and if that differs from the length recorded here,
 * the scholars at Prapatti have published a corrected PDF since this
 * build, so the app downloads the new one. That lets the check cost one
 * tiny HEAD request per Pasuram instead of re-downloading every PDF.
 *
 * Kept separate from generate-pasuram-archive.ts because it needs no
 * qpdf/zstd tooling; that script also runs this one at the end.
 *
 *   node mobile/scripts/generate-pasuram-origin.ts
 */

const MOBILE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ASSETS_ROOT = path.join(MOBILE_ROOT, "assets", "pasurams");
const OUTPUT = path.join(MOBILE_ROOT, "content-lib", "pasuram-origin.generated.ts");

function main(): void {
  const urls = allPasuramResourceUrls([...loadDivyaDesams(), ...loadBooks()]);
  const lines: string[] = [];
  for (const url of urls) {
    const file = path.join(ASSETS_ROOT, getPasuramFileName(url));
    if (!fs.existsSync(file)) continue;
    lines.push(`  ${JSON.stringify(url)}: ${fs.statSync(file).size},`);
  }

  const output = `/**
 * AUTO-GENERATED by mobile/scripts/generate-pasuram-origin.ts.
 * Do not edit by hand -- regenerate instead.
 *
 * Byte length of each original Prapatti.com PDF as bundled into this
 * build, keyed by URL. services/pasuramLatest.ts compares Prapatti's
 * current Content-Length against this to notice corrected PDFs.
 */
export const pasuramOriginLengthByUrl: Record<string, number> = {
${lines.join("\n")}
};
`;
  fs.writeFileSync(OUTPUT, output, "utf8");
  console.log(`Generated ${path.relative(path.join(MOBILE_ROOT, ".."), OUTPUT)}: ${lines.length} Pasuram PDF length(s).`);
}

main();
